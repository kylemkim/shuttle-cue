const UILang = Object.freeze({
  fromBrowser(){ const language=(navigator.language||'en').toLowerCase();return language.startsWith('ko')?'ko':language.startsWith('ja')?'ja':'en'; },
  get(locale){ return UI_I18N[locale]||UI_I18N.en; },
  text(locale,key,params={}){
    let str=this.get(locale)[key];
    if(typeof str!=='string'){console.warn('Missing UI translation',locale,key);str=UI_I18N.ko[key]||key;}
    return str.replace(/\{([\w]+)\}/g,(_,name)=>String(params[name]??''));
  },
  direction(locale,id){return this.get(locale).directionNames[id]||id;},
  stroke(locale,id){return this.get(locale).strokeNames[id]||id;},
  grip(locale,id){return this.get(locale).gripNames[id-1]||String(id);}
});
